"""The shape of the site's content, and the rules for what may be saved.

Everything the public pages say about me comes from one document with these
fields. The admin panel edits it; the API checks every save against the models
below before it reaches the database. The checks are the whole defence against
the editing form being used to put something unwelcome on the public site, so
they are strict:

  * Text is trimmed and length-limited, and lists have a size limit.
  * Links are either an https URL or a path on this site. Anything else, above
    all `javascript:` and `data:`, is rejected, because these values end up in
    an href on a page everyone visits.
  * Unknown fields are rejected, so a typo or a stale form fails loudly instead
    of being silently dropped.

The document is the source of truth only for what it contains. A field that is
absent means "use what is compiled into the site", which is how a half-filled
document or an empty database still gives a complete page.
"""

from __future__ import annotations

import re
from typing import Annotated, Literal

from pydantic import AfterValidator, BaseModel, ConfigDict, Field, StringConstraints

Label = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=60)]
Name = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=40)]
Figure = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=24)]
Line = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]
Paragraph = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=1500)]
Tag = Label

_CONTROL = re.compile(r"[\x00-\x20\x7f]")


def _check_link(value: str) -> str:
    """An https URL, or a path on this site. Nothing else."""
    value = value.strip()
    if len(value) > 300 or _CONTROL.search(value):
        raise ValueError("a link cannot contain spaces or control characters")
    if value.startswith("https://") and len(value) > len("https://"):
        return value
    if value.startswith("/") and not value.startswith("//"):
        return value
    raise ValueError("a link must start with https:// or be a path on this site such as /blog")


Link = Annotated[str, AfterValidator(_check_link)]


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)


class AvailabilityRow(_Strict):
    label: Name
    value: Line
    ok: bool = False


class Stat(_Strict):
    value: Figure
    label: Line


class Job(_Strict):
    company: Line
    role: Line
    dates: Label
    points: Annotated[list[Paragraph], Field(min_length=1, max_length=12)]
    stack: Annotated[list[Tag], Field(max_length=24)]


class Education(_Strict):
    degree: Line
    school: Line
    detail: Line
    years: Label


class SkillGroup(_Strict):
    title: Label
    items: Annotated[list[Tag], Field(min_length=1, max_length=30)]


class Project(_Strict):
    # Stable identity, so reordering and editing never confuses one project with
    # another. Generated by the admin form; the API only checks the shape.
    id: Annotated[str, StringConstraints(pattern=r"^[a-z0-9][a-z0-9-]{0,39}$")]
    tag: Label
    title: Label
    blurb: Paragraph
    # One short line for the card in the home page tunnel. When it is missing the
    # site uses the start of the blurb instead.
    tagline: Annotated[str, StringConstraints(strip_whitespace=True, max_length=90)] | None = None
    flow: Annotated[str, StringConstraints(strip_whitespace=True, max_length=240)] = ""
    extra: Annotated[str, StringConstraints(strip_whitespace=True, max_length=1500)] | None = None
    stack: Annotated[list[Tag], Field(max_length=16)] = []
    source: Link | None = None
    live: Link | None = None
    # Hidden projects stay in the admin panel but are not shown on the site.
    hidden: bool = False


JourneyIcon = Literal["cap", "chart", "briefcase", "branch", "server", "flag"]


class JourneyStop(_Strict):
    when: Label
    title: Line
    place: Line
    text: Paragraph
    stat: Stat | None = None
    tags: Annotated[list[Tag], Field(max_length=10)] | None = None
    icon: JourneyIcon
    now: bool = False


class CvInfo(_Strict):
    """Set by the server when a CV is uploaded. Never taken from a save request."""

    key: str
    filename: str
    sha256: str
    size: int
    updated_at: str


class SiteContent(_Strict):
    availability: Annotated[list[AvailabilityRow], Field(max_length=8)] | None = None
    stats: Annotated[list[Stat], Field(max_length=8)] | None = None
    job: Job | None = None
    education: Education | None = None
    skill_groups: Annotated[list[SkillGroup], Field(max_length=14)] | None = None
    projects: Annotated[list[Project], Field(max_length=40)] | None = None
    journey: Annotated[list[JourneyStop], Field(min_length=1, max_length=12)] | None = None
    cv: CvInfo | None = None

    def unique_project_ids(self) -> bool:
        ids = [p.id for p in self.projects or []]
        return len(ids) == len(set(ids))
